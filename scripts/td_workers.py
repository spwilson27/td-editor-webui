class Instance:
    """One TouchDesigner process launched by this module."""

    def __init__(self, index, toe, workdir, mcp_port, td_bin=TD_BIN, popen=subprocess.Popen, extra_env=None):
        self.index, self.toe, self.workdir, self.mcp_port, self.td_bin = index, toe, workdir, mcp_port, td_bin
        self.conn_file = os.path.join(workdir, "connection.json")
        self.log = os.path.join(workdir, "td.out")
        self.popen, self.extra_env = popen, extra_env or {}
        self.proc = None
        self.pid = None
        self.last_pid = None
        self.registry = PIDS_FILE
        self.started = None
        self.ready_seconds = None
        self.samples = []   # (t, rss_bytes, cpu_percent) of the whole process group

    def launch(self, protected=frozenset()):
        if self.popen is subprocess.Popen:
            require_td_bin(self.td_bin)
        os.makedirs(self.workdir, exist_ok=True)
        if os.path.exists(self.conn_file):
            os.remove(self.conn_file)
        env = dict(os.environ, TD_MCP_PORT=str(self.mcp_port), TD_MCP_CONNECTION=self.conn_file, **self.extra_env)
        self.proc = self.popen([self.td_bin, self.toe], env=env, start_new_session=True, cwd=self.workdir,
                               stdout=open(self.log, "w"), stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)
        self.pid = self.last_pid = self.proc.pid
        if self.pid in protected:
            raise RuntimeError(f"refusing: pid {self.pid} is a protected TouchDesigner")
        self.started = time.time()
        pids_register(self.registry, self.pid)
        return self

    def alive(self):
        return self.proc is not None and self.proc.poll() is None

    def rpc(self, code, timeout=20):
        import td_call
        conn = td_call.connection("127.0.0.1", None, self.conn_file)
        return td_call.run(code, timeout, conn)

    def wait_ready(self, timeout=120, rpc=None, sleep=time.sleep, clock=time.time):
        """Until the connection file exists and /project1 answers through td-mcp. Returns seconds; TimeoutError / RuntimeError otherwise."""
        rpc = rpc or self.rpc
        end = clock() + timeout
        t0 = clock()
        while clock() < end:
            if self.proc is not None and not self.alive():
                raise RuntimeError(f"worker {self.index}: TouchDesigner exited ({self.proc.returncode}) before it was ready; see {self.log}")
            if os.path.exists(self.conn_file):
                try:
                    res = rpc("print('ready' if op('/project1') is not None else 'noproj')", 10)
                    if res.get("ok") and "ready" in res.get("stdout", ""):
                        self.ready_seconds = round(clock() - t0, 1)
                        return self.ready_seconds
                except Exception:  # noqa: BLE001
                    pass
            sleep(0.5)
        raise TimeoutError(f"worker {self.index}: not ready after {timeout}s (a modal dialog? see {self.log})")

    def sample(self):
        """RSS (bytes) and CPU % summed over the instance's process group (TD + its web-render helpers)."""
        if self.pid is None:
            return None
        out = subprocess.run(["ps", "-axo", "pgid=,rss=,pcpu="], capture_output=True, text=True).stdout
        rss = cpu = 0.0
        for line in out.splitlines():
            p = line.split()
            if len(p) == 3 and int(p[0]) == self.pid:
                rss += float(p[1]) * 1024
                cpu += float(p[2])
        s = (time.time(), rss, cpu)
        self.samples.append(s)
        return s

    def stats(self):
        if not self.samples:
            return {}
        return {"peak_rss_gb": round(max(s[1] for s in self.samples) / GB, 2),
                "avg_cpu_percent": round(sum(s[2] for s in self.samples) / len(self.samples), 1)}

    def terminate(self, protected=frozenset(), killpg=os.killpg, grace=4.0, sleep=time.sleep):
        """SIGTERM then SIGKILL of this instance's own process group. Signals only while all hold: the pid is not protected, our Popen has
        not been reaped (so the pid cannot have been reused), it leads its own group, and that group holds a TouchDesigner process.
        Afterwards the instance is dead (pid None): a later close() / terminate() never signals again."""
        pid = self.pid
        if pid is None or pid in protected:
            return False
        if self.proc is None or self.proc.poll() is not None:
            self._mark_dead()
            return True
        try:
            if os.getpgid(pid) != pid or not group_has_td(pid):
                return False   # not the group we created (any more): do not signal
        except ProcessLookupError:
            self._mark_dead()
            return True
        for sig in (signal.SIGTERM, signal.SIGKILL):
            try:
                killpg(pid, sig)
            except ProcessLookupError:
                break
            end = time.time() + grace
            while time.time() < end and self._group_alive():
                sleep(0.2)
            if not self._group_alive():
                break
        try:
            self.proc.wait(timeout=5)
        except Exception:  # noqa: BLE001
            pass
        self._mark_dead()
        return True

    def _mark_dead(self):
        pids_remove(self.registry, self.pid)
        self.pid = None

    def _group_alive(self):
        return self.pid is not None and group_has_td(self.pid)


_CHILDREN = []
_CHILDREN_LOCK = threading.Lock()


def spawn_tracked(cmd, timeout=None, **kw):
    """Popen in its own session (so its node / Chromium children share the group), tracked for teardown; waits up to `timeout`
    seconds (then kills the group; returncode 124). Returns the finished Popen."""
    p = subprocess.Popen(cmd, start_new_session=True, **kw)
    with _CHILDREN_LOCK:
        _CHILDREN.append(p)
    try:
        p.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        kill_child(p)
        p.returncode = 124
    return p


def kill_child(p, grace=3.0, killpg=os.killpg):
    """Kill the group of a tracked child we started (only while it has not been reaped, so its pid cannot be reused)."""
    for sig in (signal.SIGTERM, signal.SIGKILL):
        if p.poll() is not None:
            break
        try:
            killpg(p.pid, sig)
        except (ProcessLookupError, PermissionError):
            break
        try:
            p.wait(timeout=grace)
        except subprocess.TimeoutExpired:
            pass


def kill_children():
    with _CHILDREN_LOCK:
        kids = list(_CHILDREN)
    for p in kids:
        try:
            kill_child(p)
        except Exception:  # noqa: BLE001
            pass


class Fleet:
    """The launched instances + guaranteed teardown (context manager, atexit, SIGINT / SIGTERM). close() cannot be interrupted by a
    second signal, survives a failing terminate, and can be called again until every instance is gone."""

    SIGNALS = (signal.SIGINT, signal.SIGTERM, signal.SIGHUP)

    def __init__(self, protected=None, keep=False):
        self.instances = []
        self.protected = set(protected if protected is not None else td_pids())
        self.keep = keep
        self._prev = {}
        self._done = False
        self._closing = False

    def add(self, inst):
        self.instances.append(inst)
        return inst

    def close(self):
        if self._done or self._closing:
            return
        self._closing = True
        held = {}
        for sig in self.SIGNALS:   # a second Ctrl-C must not abort the cleanup
            try:
                held[sig] = signal.signal(sig, signal.SIG_IGN)
            except ValueError:
                pass
        try:
            try:
                kill_children()
            except Exception as e:  # noqa: BLE001
                print(f"teardown: validator subprocesses: {e!r}")
            ok = True
            for i in self.instances:
                if self.keep:
                    if i.pid is not None:
                        print(f"kept: worker {i.index} pid {i.pid} td-mcp {i.mcp_port} conn {i.conn_file} (kill: kill -9 -{i.pid})")
                    continue
                try:
                    i.terminate(self.protected)
                except Exception as e:  # noqa: BLE001
                    ok = False
                    print(f"teardown: worker {i.index} pid {i.pid}: {e!r}")
            self._done = ok
        finally:
            for sig, h in held.items():
                try:
                    signal.signal(sig, h)
                except Exception:  # noqa: BLE001
                    pass
            self._closing = False

    def __enter__(self):
        atexit.register(self.close)
        for sig in self.SIGNALS:
            try:
                self._prev[sig] = signal.signal(sig, self._on_signal)
            except ValueError:   # not the main thread
                pass
        return self

    def _on_signal(self, signum, frame):
        if self._closing:
            return
        self.close()
        if signum == signal.SIGINT:
            raise KeyboardInterrupt
        sys.exit(128 + signum)

    def __exit__(self, *exc):
        self.close()
        for sig, h in self._prev.items():
            try:
                signal.signal(sig, h)
            except Exception:  # noqa: BLE001
                pass
        return False


class ConnGuard:
    """~/.td-mcp/connection.json must never change during an isolated run (a worker running an old plugin would overwrite it)."""

    def __init__(self, path=USER_CONN_FILE):
        self.path = path
        self.before = self._read()

    def _read(self):
        try:
            with open(self.path, "rb") as f:
                return f.read()
        except OSError:
            return None

    def changed(self):
        return self._read() != self.before

    def check(self):
        """Restore the file and raise when it changed."""
        if not self.changed():
            return
        if self.before is None:
            try:
                os.remove(self.path)
            except OSError:
                pass
        else:
            with open(self.path, "wb") as f:
                f.write(self.before)
            os.chmod(self.path, 0o600)
        raise WorkerError(f"{self.path} was modified during the run: a worker is running an old td-mcp plugin without TD_MCP_CONNECTION "
                          "support. The file was restored; nothing was run.")


class WorkerError(RuntimeError):
    pass


def launch_fleet(n, toe=VALIDATE_TOE, workroot=VDIR, fleet=None, ready_timeout=120, ports=None, make=Instance, log=print):
    """Launch + wait for n instances (parallel start; each with a private copy of the toe). Returns the ready instances."""
    ports = ports or pick_ports(n)
    insts = []
    for i in range(n):
        wd = os.path.join(workroot, f"w{i}")
        os.makedirs(wd, exist_ok=True)
        dst = os.path.join(wd, "validate.toe")
        shutil.copyfile(toe, dst)
        inst = make(i, dst, wd, ports[i])
        insts.append(fleet.add(inst) if fleet else inst)
        inst.launch(fleet.protected if fleet else frozenset())
        log(f"worker {i}: pid {inst.pid}, td-mcp 127.0.0.1:{inst.mcp_port}")
    errors = []

    def wait(inst):
        try:
            s = inst.wait_ready(ready_timeout)
            log(f"worker {inst.index}: ready in {s}s")
        except Exception as e:  # noqa: BLE001
            errors.append(e)

    threads = [threading.Thread(target=wait, args=(x,)) for x in insts]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    if errors:
        raise errors[0]
    return insts


# --------------------------------------------------------------------------- running shards


def validator_cmd(steps, inst_or_none, json_path, args):
    cmd = [sys.executable, os.path.join(ROOT, "scripts", "validate_td.py"), "--only", ",".join(map(str, steps)), "--json", json_path,
           "--page", args.page]
    if inst_or_none is not None:
        cmd += ["--td-conn", inst_or_none.conn_file, "--td-port", str(inst_or_none.mcp_port)]
    else:
        cmd += ["--td-port", str(args.td_port)]
    if args.no_build:
        cmd.append("--no-build")
    if args.skip_ui:
        cmd.append("--skip-ui")
    return cmd


def shard_timeout(steps, durations, fill=20.0):
    """Seconds a shard may take: its estimate x 3 + 300."""
    return sum(float(durations.get(x, fill) or fill) for x in steps) * 3 + 300


def run_shard(steps, inst, label, outdir, args, spawn=spawn_tracked):
    """One validate_td.py subprocess (tracked, in its own session, killed on timeout / teardown); -> (result dicts, returncode).
    A crash or timeout that wrote no JSON gives a failed pseudo result per step."""
    jp = os.path.join(outdir, f"{label}.json")
    if os.path.exists(jp):
        os.remove(jp)
    logp = os.path.join(outdir, f"{label}.log")
    env = dict(os.environ)
    if inst is not None:
        env["TD_MCP_CONNECTION"] = inst.conn_file
    timeout = shard_timeout(steps, getattr(args, "_durations", {}) or {})
    with open(logp, "w") as lf:
        r = spawn(validator_cmd(steps, inst, jp, args), timeout=timeout, cwd=ROOT, env=env, stdout=lf, stderr=subprocess.STDOUT)
    rc = getattr(r, "returncode", 1)
    try:
        with open(jp, encoding="utf-8") as f:
            doc = json.load(f)
        results = doc.get("steps", [])
    except (OSError, ValueError):
        why = f"timed out after {timeout:.0f}s" if rc == 124 else f"exit {rc}"
        results = [{"num": s, "name": f"(shard {label} crashed, see {logp})", "status": "fail", "seconds": 0.0, "details": f"no summary written ({why})",
                    "timing": False} for s in steps]
    return results, rc


def run_parallel(shards, insts, outdir, args, runner=run_shard):
    """Run every non-empty shard in its own thread; an exception in one marks that shard's steps failed (never lost)."""
    out, lock = [], threading.Lock()

    def work(i):
        steps = shards[i]
        if not steps:
            return
        try:
            res, _ = runner(steps, insts[i], f"w{i}", outdir, args)
        except BaseException as e:  # noqa: BLE001
            res = [{"num": x, "name": f"(shard w{i} raised)", "status": "fail", "seconds": 0.0, "details": f"{type(e).__name__}: {e}",
                    "timing": False} for x in steps]
        with lock:
            out.append((i, res))

    ts = [threading.Thread(target=work, args=(i,)) for i in range(len(shards))]
    for t in ts:
        t.start()
    for t in ts:
        t.join()
    return out


def add_missing(results, expected, names=None):
    """Every expected step without a result becomes a FAIL ('no result from shard'). Returns the new list (sorted)."""
    have = {r["num"] for r in results}
    out = list(results)
    for n in sorted(set(expected) - have):
        out.append({"num": n, "name": (names or {}).get(n, f"step {n}"), "status": "fail", "seconds": 0.0, "details": "no result from shard",
                    "timing": False, "worker": "-"})
    return sorted(out, key=lambda r: r["num"])


EDITOR_PORT_BASE = 9990
EDITOR_PORT_STEP = 20


def pick_editor_ports(n, base=EDITOR_PORT_BASE, step=EDITOR_PORT_STEP, is_free=port_free):
    """One editor web port per worker (spaced `step` apart so each keeps room for the editor's own +1..+50 fallback)."""
    out, p = [], base
    while len(out) < n:
        if all(is_free(p + k) for k in range(0, 3)):
            out.append(p)
            p += step
        else:
            p += 1
    return out


def prebuild(insts, ports, outdir, args, runner=run_shard, wait=time.sleep, timeout=30):
    """Phase A, one worker at a time (two editors starting together would both claim the default port 9980): build the COMP (step 1),
    then give its master the worker's own editor port. Returns [(worker, results)]; WorkerError when a build or the port change fails."""
    out = []
    for inst, port in zip(insts, ports):
        if not args.no_build:
            res, _ = runner([1], inst, f"build{inst.index}", outdir, args)
            out.append((inst.index, res))
            r1 = [r for r in res if r.get("num") == 1]
            if not r1 or r1[0].get("status") == "fail":
                raise WorkerError(f"worker {inst.index}: building the raster editor failed: {(r1[0].get('details') if r1 else 'no result')!s:.300}")
        code = ("c = op('/project1/raster_editor')\nc.par.Port = %d\nprint('port', c.par.Port.eval())" % port)
        r = inst.rpc(code, 30)
        if not r.get("ok"):
            raise WorkerError(f"worker {inst.index}: could not set the editor port {port}: {str(r.get('error') or r.get('traceback'))[-300:]}")
        end = time.time() + timeout
        got = None
        while True:
            r = inst.rpc("import json\nprint(json.dumps(op('/').fetch('rasterEditorMaster', None)))", 15)
            try:
                rec = json.loads(r.get("stdout", "").strip().splitlines()[-1]) if r.get("ok") else None
            except Exception:  # noqa: BLE001
                rec = None
            got = rec.get("port") if rec else None
            if got == port:
                break
            if time.time() >= end:
                raise WorkerError(f"worker {inst.index}: the editor master did not move to port {port} within {timeout}s (record: {got})")
            wait(0.5)
        inst.editor_port = port
    return out


# --------------------------------------------------------------------------- reporting


def format_table(results, wall, workers_info=None):
    lines = [f"{'step':>4}  {'status':<6} {'sec':>7}  worker  name"]
    for r in results:
        lines.append(f"{r['num']:>4}  {r['status']:<6} {r['seconds']:>7.1f}  {str(r.get('worker', '-')):>6}  {r['name'][:90]}")
        if r["status"] == "fail" and r.get("details") in ("no result from shard",):
            lines.append(f"{'':>26}{r['details']}")
    p = sum(r["status"] == "pass" for r in results)
    f = sum(r["status"] == "fail" for r in results)
    s = sum(r["status"] == "skip" for r in results)
    lines.append(f"\n{p} passed, {f} failed, {s} skipped; wall {wall:.0f}s; sum of step times {sum(r['seconds'] for r in results):.0f}s")
    for w in workers_info or []:
        lines.append(f"worker {w['worker']}: ready {w.get('ready_seconds')}s, shard {w.get('shard_seconds', '?')}s, peak RSS {w.get('peak_rss_gb', '?')} GB, "
                     f"avg CPU {w.get('avg_cpu_percent', '?')}%")
    return "\n".join(lines)


def write_summary(path, results, wall, workers_info, args):
    doc = {"mode": "attach" if args.attach else "isolated", "workers": len(workers_info), "tier": args.tier, "wall_seconds": round(wall, 1),
           "passed": sum(r["status"] == "pass" for r in results), "failed": sum(r["status"] == "fail" for r in results),
           "skipped": sum(r["status"] == "skip" for r in results), "steps": results,
           "durations": {str(r["num"]): r["seconds"] for r in results}, "worker_stats": workers_info}
    with open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1)


def update_last(path, results):
    """Merge the durations of this run into `path` (the bin-packing record): failed and zero-duration results keep the previous value."""
    prev = load_durations(path)
    for r in results:
        if r.get("status") != "fail" and float(r.get("seconds") or 0) > 0:
            prev[int(r["num"])] = float(r["seconds"])
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump({"durations": {str(k): v for k, v in sorted(prev.items())}}, f, indent=1)
    os.replace(tmp, path)


def scrub_tokens(paths, tokens):
    """Replace every td-mcp token in the text files under `paths` (logs, summaries) by <token>. Returns the files changed."""
    tokens = [t for t in tokens if t]
    changed = []
    for root in paths:
        for dp, _, files in os.walk(root):
            for fn in files:
                if not fn.endswith((".log", ".json", ".out")) or fn == "connection.json":
                    continue
                fp = os.path.join(dp, fn)
                try:
                    txt = open(fp, encoding="utf-8", errors="replace").read()
                except OSError:
                    continue
                new = txt
                for t in tokens:
                    new = new.replace(t, "<token>")
                if new != txt:
                    open(fp, "w", encoding="utf-8").write(new)
                    changed.append(fp)
    return changed


def conn_tokens(insts):
    out = []
    for i in insts:
        try:
            out.append(json.load(open(i.conn_file)).get("token"))
        except (OSError, ValueError):
            pass
    return out


