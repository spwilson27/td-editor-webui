"""Parallel, isolated TouchDesigner validation (docs/VALIDATION.md, option 2).

    .venv/bin/python scripts/td_workers.py                      # 3 isolated TD instances (capped by free RAM), full suite
    .venv/bin/python scripts/td_workers.py --workers 1          # one isolated instance (the user's project is still untouched)
    .venv/bin/python scripts/td_workers.py --tier smoke --keep  # leave the instances running afterwards (debugging)
    .venv/bin/python scripts/td_workers.py --attach             # no launch: the user's TD on 8765 (today's behaviour)

Each worker is a NEW TouchDesigner process opening .validate/<n>/validate.toe (generated by make_validate_toe.py: the td-mcp debug
server and nothing else). Per instance: its own td-mcp port + connection file (env TD_MCP_PORT / TD_MCP_CONNECTION, read by the td-mcp
plugin) -- the user's ~/.td-mcp/connection.json is never written. The raster editor is built fresh from dist/raster_editor.tox by
validation step 1 in every worker, and its web server takes a free port by itself (master port fallback).

Safety: only the PIDs launched here are ever signalled (process group = the launcher's pid, verified before every kill); the TD
processes that already run (the user's, e.g. the one listening on 8765) are recorded at start and can never be targeted.
"""

