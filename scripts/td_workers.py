# --------------------------------------------------------------------------- machine facts


def parse_vm_stat(out):
    """Free + inactive + speculative bytes from `vm_stat` output (purgeable pages are already inside inactive/active: not added)."""
    size = int(re.search(r"page size of (\d+) bytes", out).group(1))
    pages = 0
    for key in ("Pages free", "Pages inactive", "Pages speculative"):
        m = re.search(rf"{key}:\s+(\d+)", out)
        if m:
            pages += int(m.group(1))
    return pages * size


def free_ram_bytes():
    """Memory available for new instances (macOS vm_stat), bytes; None when unknown."""
    try:
        return parse_vm_stat(subprocess.run(["vm_stat"], capture_output=True, text=True, timeout=10).stdout)
    except Exception:  # noqa: BLE001
        return None


def cap_workers(requested, free_bytes, ncpu, per_instance=PER_INSTANCE_BYTES, reserve=RAM_RESERVE_BYTES, steps=None):
    """(workers, reason): `requested` limited by free RAM (minus a reserve), by CPUs (>= 4 per instance) and by the shardable steps."""
    n, reason = max(1, int(requested)), ""
    if free_bytes is not None:
        by_ram = max(1, int((free_bytes - reserve) // per_instance))
        if by_ram < n:
            n, reason = by_ram, f"free RAM {free_bytes / GB:.0f} GB"
    if ncpu:
        by_cpu = max(1, ncpu // 4)
        if by_cpu < n:
            n, reason = by_cpu, f"{ncpu} CPUs"
    if steps is not None and 0 < steps < n:
        n, reason = steps, f"only {steps} steps"
    return n, reason


def port_free(port, host="127.0.0.1"):
    with socket.socket() as s:
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


def pick_ports(n, base=BASE_MCP_PORT, is_free=port_free):
    ports, p = [], base
    while len(ports) < n:
        if p != USER_PORT and is_free(p):
            ports.append(p)
        p += 1
    return ports


def is_td_main(cmd):
    return (cmd == TD_BIN or cmd.startswith(TD_BIN + " ")) and "Web Render" not in cmd and "Helper" not in cmd


def td_pids():
    """PIDs of every running TouchDesigner main process (the user's included): never touched."""
    out = subprocess.run(["ps", "-axo", "pid=,command="], capture_output=True, text=True).stdout
    pids = set()
    for line in out.splitlines():
        pid, _, cmd = line.strip().partition(" ")
        if is_td_main(cmd.strip()):
            pids.add(int(pid))
    return pids


def group_has_td(pgid):
    """True when process group `pgid` holds a TouchDesigner process (main, web-render or helper): the guard before every killpg."""
    try:
        out = subprocess.run(["ps", "-axo", "pgid=,command="], capture_output=True, text=True, timeout=10).stdout
    except Exception:  # noqa: BLE001
        return False
    for line in out.splitlines():
        pg, _, cmd = line.strip().partition(" ")
        if pg.isdigit() and int(pg) == pgid and (cmd.startswith(TD_BIN) or "/TouchDesigner.app/Contents/" in cmd):
            return True
    return False


def proc_info(pid):
    """(start time string, command) of a live pid, or None."""
    try:
        a = subprocess.run(["ps", "-o", "lstart=", "-p", str(pid)], capture_output=True, text=True, timeout=10).stdout.strip()
        c = subprocess.run(["ps", "-o", "command=", "-p", str(pid)], capture_output=True, text=True, timeout=10).stdout.strip()
    except Exception:  # noqa: BLE001
        return None
    return (a, c) if a and c else None


_PIDS_LOCK = threading.Lock()


def _read_pids(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return []


def _write_pids(path, entries):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(entries, f)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


def pids_register(path, pid, info=None):
    """Record a launched instance (pid, pgid, start time, command) so a crashed run's orphans can be found next time."""
    if not path:
        return
    info = info or proc_info(pid) or ("", "")
    with _PIDS_LOCK:
        entries = [e for e in _read_pids(path) if e.get("pid") != pid]
        entries.append({"pid": pid, "pgid": pid, "start": info[0], "cmd": info[1]})
        os.makedirs(os.path.dirname(path), exist_ok=True)
        _write_pids(path, entries)


def pids_remove(path, pid):
    if not path:
        return
    with _PIDS_LOCK:
        _write_pids(path, [e for e in _read_pids(path) if e.get("pid") != pid]) if os.path.exists(path) else None


def find_orphans(path, protected=frozenset(), info=proc_info):
    """Entries of a previous run whose pid is still the same process (start time + command match, a TouchDesigner main)."""
    out = []
    for e in _read_pids(path):
        cur = info(e.get("pid"))
        if cur and cur == (e.get("start"), e.get("cmd")) and is_td_main(cur[1]) and e["pid"] not in protected:
            out.append(e)
    return out


def kill_group_checked(pid, killpg=os.killpg, getpgid=os.getpgid, sleep=time.sleep, grace=4.0):
    """SIGTERM then SIGKILL of group `pid` -- only when the pid leads its own group and that group holds a TouchDesigner process."""
    try:
        if getpgid(pid) != pid or not group_has_td(pid):
            return False
    except ProcessLookupError:
        return True
    for sig in (signal.SIGTERM, signal.SIGKILL):
        try:
            killpg(pid, sig)
        except ProcessLookupError:
            return True
        except PermissionError:
            return False
        end = time.time() + grace
        while time.time() < end and group_has_td(pid):
            sleep(0.2)
        if not group_has_td(pid):
            break
    return True


def cleanup_orphans(path=PIDS_FILE, protected=frozenset(), ask=None, log=print, find=find_orphans, kill=kill_group_checked):
    """Offer to kill instances left by a crashed earlier run (`ask()` -> bool; None = report only). Returns the number killed."""
    orphans = find(path, protected)
    killed = 0
    if orphans:
        log(f"found {len(orphans)} TouchDesigner instance(s) from an earlier run: pids {[e['pid'] for e in orphans]}")
        if ask is not None and ask():
            for e in orphans:
                if kill(e["pid"]):
                    killed += 1
        else:
            log("  left running (re-run with --clean-orphans to kill them)")
    if os.path.exists(path) and (killed == len(orphans)):
        try:
            os.remove(path)
        except OSError:
            pass
    return killed


def listener_pid(port):
    r = subprocess.run(["lsof", "-nP", f"-iTCP:{port}", "-sTCP:LISTEN", "-t"], capture_output=True, text=True)
    return {int(x) for x in r.stdout.split()}


# --------------------------------------------------------------------------- sharding


def shard_steps(steps, durations, n, default=None):
    """Longest-processing-time-first bin packing: `steps` over `n` shards by recorded `durations` ({num: seconds}); steps with no
    record count as the median (or `default`); with no records at all, equal split (round robin in step order).
    Returns n lists (step numbers ascending inside each shard); empty shards are kept."""
    steps = list(steps)
    n = max(1, n)
    known = sorted(float(durations[s]) for s in steps if s in durations and durations[s] is not None)
    if not known:
        shards = [[] for _ in range(n)]
        for i, s in enumerate(steps):
            shards[i % n].append(s)
        return shards
    fill = default if default is not None else known[len(known) // 2]
    cost = {s: float(durations.get(s) if durations.get(s) is not None else fill) for s in steps}
    shards, load = [[] for _ in range(n)], [0.0] * n
    for s in sorted(steps, key=lambda s: (-cost[s], s)):
        i = min(range(n), key=lambda k: (load[k], k))
        shards[i].append(s)
        load[i] += cost[s]
    return [sorted(sh) for sh in shards]


def shard_load(shard, durations, fill=0.0):
    return sum(float(durations.get(s, fill) or fill) for s in shard)


def load_durations(path):
    """{step: seconds} from a validate_td.py --json summary (or a workers summary); {} when unreadable."""
    try:
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
    except (OSError, ValueError):
        return {}
    d = doc.get("durations")
    if isinstance(d, dict):
        return {int(k): float(v) for k, v in d.items() if v is not None}
    return {int(s["num"]): float(s["seconds"]) for s in doc.get("steps", []) if "num" in s and "seconds" in s}


def plan_steps(nums, timing, no_timing=False, prelude=PRELUDE_STEPS, last=(99,)):
    """-> (parallel, tail): the shardable steps (the prelude is prepended to every shard instead) and the steps that run afterwards on
    one idle worker, alone: the 'timing' steps (dropped by no_timing), then `last` (step 99 deletes the component and restores it, so
    nothing may run after it on that instance)."""
    nums = sorted(set(nums))
    t = [n for n in nums if n in timing and n not in last]
    tail_last = [n for n in nums if n in last]
    par = [n for n in nums if n not in timing and n not in prelude and n not in last]
    return par, ([] if no_timing else t) + tail_last


def shard_commands(shards, prelude=PRELUDE_STEPS):
    """Step lists a worker runs: the prelude first (when the worker has anything to run), then its shard."""
    return [(list(prelude) + sh) if sh else [] for sh in shards]


def merge_results(per_worker, prelude=PRELUDE_STEPS):
    """per_worker: [(worker_index, [result dict, ...])] -> one list sorted by step. A prelude step run on every worker is reported once
    (worst status wins; the longest time is kept); each result gets 'worker'."""
    merged = {}
    rank = {"fail": 2, "pass": 1, "skip": 0}
    for w, results in per_worker:
        for r in results:
            r = dict(r, worker=w)
            cur = merged.get(r["num"])
            if cur is None:
                merged[r["num"]] = r
            else:
                if rank.get(r["status"], 0) > rank.get(cur["status"], 0):
                    keep = dict(r)
                    keep["seconds"] = max(r["seconds"], cur["seconds"])
                    merged[r["num"]] = keep
                else:
                    cur["seconds"] = max(r["seconds"], cur["seconds"])
    return [merged[k] for k in sorted(merged)]


