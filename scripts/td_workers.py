def select_steps(args, vt):
    if args.only:
        return [int(x) for x in args.only.split(",") if x.strip()]
    if args.tier == "smoke":
        return list(vt.SMOKE)
    if args.tier == "affected":
        nums, areas, changed = vt.affected_steps()
        print(f"affected: {len(changed)} changed files -> areas {areas} -> steps {nums}")
        return nums
    return [n for n, *_ in vt.STEPS]


def main(argv=None, vt=None):
    try:
        return _main(argv, vt)
    except WorkerError as e:
        print(f"error: {e}", file=sys.stderr)
        return 3


def _main(argv=None, vt=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--workers", type=int, default=3, help="isolated TouchDesigner instances (default 3, capped by free RAM / CPUs)")
    ap.add_argument("--tier", choices=["smoke", "affected", "full"], default=None)
    ap.add_argument("--only", default="", help="comma separated step numbers")
    ap.add_argument("--no-timing", action="store_true", help="skip the timing-budget steps")
    ap.add_argument("--keep", action="store_true", help="leave the launched instances running (debugging)")
    ap.add_argument("--attach", action="store_true", help="no launch: run everything in the TD already open on --td-port (the user's project)")
    ap.add_argument("--td-port", type=int, default=USER_PORT, help="--attach: td-mcp port (default 8765)")
    ap.add_argument("--durations", default=None, help="a previous --json summary for the bin packing (default: .validate/last.json if present)")
    ap.add_argument("--page", choices=["playwright", "webrender"], default="playwright")
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--skip-ui", action="store_true")
    ap.add_argument("--ready-timeout", type=float, default=120)
    ap.add_argument("--clean-orphans", action="store_true", help="kill TouchDesigner instances left by an earlier crashed run (else asked on a tty)")
    ap.add_argument("--toe", default=VALIDATE_TOE, help="validation project (generated by make_validate_toe.py when missing)")
    ap.add_argument("--json", default=None, help="write the merged summary here (also .validate/last.json)")
    args = ap.parse_args(argv)
    vt = vt or load_validator()
    os.makedirs(VDIR, exist_ok=True)
    outdir = os.path.join(VDIR, "runs", time.strftime("%Y%m%d-%H%M%S"))
    os.makedirs(outdir, exist_ok=True)

    nums = select_steps(args, vt)
    known = {n for n, *_ in vt.STEPS}
    unknown = sorted(set(nums) - known)
    if unknown:
        print(f"error: unknown step(s) {unknown}; known: {sorted(known)}", file=sys.stderr)
        return 2
    names = {n: name for n, name, *_ in vt.STEPS}
    timing_set = set(vt.TIMING)
    par, tim = plan_steps(nums, timing_set, args.no_timing, last=(getattr(vt, "LAST", 99),))
    durations = load_durations(args.durations or os.path.join(VDIR, "last.json"))
    args._durations = durations
    expected = set(par) | set(tim) | ({1} if 1 in nums else set())
    t0 = time.time()
    workers_info, per_worker = [], []

    if args.attach:
        print(f"attach: everything in the TouchDesigner on 127.0.0.1:{args.td_port} (the user's project)")
        steps = vt.order_steps(nums, args.no_timing)
        res, _ = run_shard(steps, None, "attach", outdir, args)
        per_worker.append((0, res))
        workers_info.append({"worker": 0, "shard_seconds": round(time.time() - t0, 1)})
    else:
        if not os.path.exists(args.toe):
            import make_validate_toe
            make_validate_toe.generate(args.toe)
        n, why = cap_workers(args.workers, free_ram_bytes(), os.cpu_count(), steps=max(1, len(par)))
        if n < args.workers:
            print(f"workers: {args.workers} requested, using {n} ({why})")
        user = listener_pid(USER_PORT)
        ask = (lambda: True) if args.clean_orphans else ((lambda: input("kill them? [y/N] ").strip().lower() == "y") if sys.stdin.isatty() else None)
        cleanup_orphans(PIDS_FILE, td_pids() | user, ask)
        guard = ConnGuard()
        print(f"protected (never touched): TouchDesigner pids {sorted(td_pids())}; port {USER_PORT} owner {sorted(user)}")
        with Fleet(protected=td_pids() | user, keep=args.keep) as fleet:
            insts = launch_fleet(n, args.toe, VDIR, fleet, args.ready_timeout)
            guard.check()
            per_worker += prebuild(insts, pick_editor_ports(n), outdir, args)
            args.no_build = True   # every shard below reuses the COMP built (and given its port) above
            stop = threading.Event()

            def sampler():
                while not stop.wait(2.0):
                    for i in insts:
                        i.sample()

            threading.Thread(target=sampler, daemon=True).start()
            try:
                shards = shard_steps(par, durations, n)
                cmds = shard_commands(shards)
                for i, c in enumerate(cmds):
                    print(f"shard {i}: {c} (est {shard_load(shards[i], durations):.0f}s)")
                t1 = time.time()
                per_worker += run_parallel(cmds, insts, outdir, args)
                shard_secs = round(time.time() - t1, 1)
                tsecs = 0.0
                if tim:
                    print(f"tail steps {tim} (timing, then the destructive last one): a fresh, idle instance (worker 0 relaunched)")
                    t2 = time.time()
                    old = insts[0]
                    old.terminate(fleet.protected)
                    fresh = launch_fleet(1, args.toe, VDIR, fleet, args.ready_timeout)[0]
                    guard.check()
                    insts[0] = fresh   # the sampler keeps measuring the replacement
                    build_args = argparse.Namespace(**dict(vars(args), no_build=False))
                    prebuild([fresh], [getattr(old, "editor_port", EDITOR_PORT_BASE)], outdir, build_args)
                    res, _ = run_shard(list(PRELUDE_STEPS) + list(tim), fresh, "timing", outdir, args)
                    per_worker.append((0, [r for r in res if r["num"] in set(tim)]))
                    tsecs = round(time.time() - t2, 1)
                for i in insts:
                    workers_info.append(dict({"worker": i.index, "mcp_port": i.mcp_port, "pid": i.pid or i.last_pid, "ready_seconds": i.ready_seconds,
                                              "shard_seconds": shard_secs, "timing_seconds": tsecs, "editor_port": getattr(i, "editor_port", None)}, **i.stats()))
            finally:
                stop.set()
                tokens = conn_tokens(fleet.instances)
                for i in fleet.instances:
                    try:
                        os.chmod(i.conn_file, 0o600)
                    except OSError:
                        pass
                guard_err = None
                try:
                    guard.check()
                except WorkerError as e:
                    guard_err = e
            if guard_err:
                raise guard_err
            scrub_tokens([outdir] + [os.path.join(VDIR, f"w{i}") for i in range(n)], tokens)

    wall = time.time() - t0
    results = add_missing(merge_results(per_worker), expected, names)
    print("\n" + format_table(results, wall, workers_info))
    summary = args.json or os.path.join(outdir, "summary.json")
    write_summary(summary, results, wall, workers_info, args)
    if not args.attach:
        update_last(os.path.join(VDIR, "last.json"), results)
    print(f"summary: {summary}")
    return 1 if any(r["status"] == "fail" for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
